-- The tag register. Single source of truth for the generator's operating
-- envelope, the rule engine's thresholds, and the app's tag metadata.
CREATE OR REPLACE TABLE jack_freeman_catalog.tech_summit_scada_build.dim_tag (
  tag_id           STRING  NOT NULL COMMENT 'e.g. CRU-PCR01-VI01',
  asset_id         STRING  NOT NULL COMMENT 'e.g. CRU-PCR01',
  asset_name       STRING  NOT NULL,
  asset_type       STRING  NOT NULL COMMENT 'crusher|screen|conveyor|bin|cyclone|stacker|feeder|thickener|sampler|utility',
  area_code        STRING  NOT NULL COMMENT 'ROM|CRU|SCR|DSD|STK|UTL|LAB',
  area_name        STRING  NOT NULL,
  measure          STRING  NOT NULL COMMENT 'mass_flow|vibration|temperature|...',
  instrument_type  STRING  NOT NULL COMMENT 'ISA-5.1-style code: WI|VI|TI|...',
  unit             STRING  NOT NULL,
  value_class      STRING  NOT NULL COMMENT 'analog|discrete',
  sample_hz        DOUBLE  NOT NULL COMMENT 'nominal sample rate; 10 Hz for vibration, 0.00056 for hourly lab',
  nominal          DOUBLE          COMMENT 'design operating point; generator centres here',
  lo_lo            DOUBLE          COMMENT 'trip limit, low',
  lo               DOUBLE          COMMENT 'warning limit, low',
  hi               DOUBLE          COMMENT 'warning limit, high',
  hi_hi            DOUBLE          COMMENT 'trip limit, high',
  is_mass_balance  BOOLEAN NOT NULL COMMENT 'feeds a flowsheet arc measurement',
  is_pdm           BOOLEAN NOT NULL COMMENT 'feeds the predictive maintenance feature set',
  enum_values      STRING          COMMENT 'pipe-delimited states for discrete tags',
  description      STRING,
  CONSTRAINT pk_dim_tag PRIMARY KEY (tag_id) RELY
) COMMENT 'Tag register. Regenerate via gen_reference_data.py, do not edit by hand.';

CREATE OR REPLACE TABLE jack_freeman_catalog.tech_summit_scada_build.dim_flowsheet_node (
  node_id             STRING  NOT NULL,
  node_name           STRING  NOT NULL,
  node_type           STRING  NOT NULL,
  area_code           STRING  NOT NULL,
  balance_role        STRING  NOT NULL COMMENT 'source|unit|sink. Only unit nodes are expected to close.',
  accumulation_tag_id STRING          COMMENT 'level tag, where the node holds inventory (bins, thickener)',
  capacity_t          DOUBLE          COMMENT 'live capacity in tonnes at 100% level; 0 where not applicable',
  layout_x            INT     NOT NULL COMMENT 'grid position for the app flowsheet',
  layout_y            INT     NOT NULL,
  CONSTRAINT pk_node PRIMARY KEY (node_id) RELY
) COMMENT 'Unit operations in the mass balance. The app draws from this, nothing is hardcoded in the UI.';

CREATE OR REPLACE TABLE jack_freeman_catalog.tech_summit_scada_build.dim_flowsheet_arc (
  arc_id         STRING  NOT NULL,
  from_node_id   STRING  NOT NULL,
  to_node_id     STRING  NOT NULL,
  arc_name       STRING  NOT NULL,
  design_tph     DOUBLE  NOT NULL COMMENT 'design basis tonnage, for deviation comparison',
  measure_tag_id STRING          COMMENT 'tag that measures this stream; NULL means inferred',
  measure_method STRING  NOT NULL COMMENT 'weightometer|slurry_flow_density|volume_flow|inferred',
  stream_type    STRING  NOT NULL COMMENT 'dry_solids|slurry|water',
  CONSTRAINT pk_arc PRIMARY KEY (arc_id) RELY,
  CONSTRAINT fk_arc_from FOREIGN KEY (from_node_id) REFERENCES jack_freeman_catalog.tech_summit_scada_build.dim_flowsheet_node,
  CONSTRAINT fk_arc_to   FOREIGN KEY (to_node_id)   REFERENCES jack_freeman_catalog.tech_summit_scada_build.dim_flowsheet_node
) COMMENT 'Material streams between nodes and the tag measuring each.';

CREATE OR REPLACE TABLE jack_freeman_catalog.tech_summit_scada_build.dim_rule (
  rule_id          STRING  NOT NULL,
  rule_name        STRING  NOT NULL,
  scope_type       STRING  NOT NULL COMMENT 'all|measure|asset_type|tag|node',
  scope_value      STRING          COMMENT 'the measure/asset_type/tag_id the rule applies to',
  rule_type        STRING  NOT NULL COMMENT 'limit_trip|limit_warn|rate_of_change|deviation|stale|imbalance|quality',
  severity         STRING  NOT NULL COMMENT 'CRITICAL|HIGH|WARNING|INFO',
  window_seconds   INT     NOT NULL COMMENT '0 for instantaneous rules',
