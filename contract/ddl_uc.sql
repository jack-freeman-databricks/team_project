-- ---------------------------------------------------------------------
-- A.2  The bronze reading contract, and the seed table that unblocks
--      lanes B and C before the live stream exists.
--
--      This shape is what the generator emits, what lands in Lakebase,
--      and what vw_tag_reading exposes. Agree it in phase 0 and freeze it:
--      it is the single dependency between all three lanes.
-- ---------------------------------------------------------------------
CREATE OR REPLACE TABLE jack_freeman_catalog.tech_summit_scada_build.tag_reading_seed (
  event_id   STRING    NOT NULL COMMENT 'uuid4, idempotency key',
  tag_id     STRING    NOT NULL,
  source_ts  TIMESTAMP NOT NULL COMMENT 'when the instrument sampled',
  value      DOUBLE             COMMENT 'analog value; NULL for discrete tags',
  value_text STRING             COMMENT 'discrete state; NULL for analog tags',
  quality    STRING    NOT NULL COMMENT 'GOOD|BAD|UNCERTAIN|STALE',
  unit       STRING    NOT NULL COMMENT 'denormalised from dim_tag, as OPC-UA carries it',
  seq        BIGINT    NOT NULL COMMENT 'monotonic per tag, breaks ordering ties',
  producer   STRING    NOT NULL COMMENT 'generator instance id',
  ingest_ts  TIMESTAMP NOT NULL
)
CLUSTER BY (tag_id, source_ts)
COMMENT 'Static 24h synthetic sample. Lane A populates in phase 0 so lanes B and C are never blocked. Same shape as the live path.';

-- Long-horizon seed for model training. The 24h reading seed above cannot
-- train a predictive maintenance model, so lane A also generates 120 days of
-- 10-minute vibration features directly, including the injected failure events
-- described in contract/naming.md. Same columns as the SDP-managed
-- jack_freeman_catalog.tech_summit_scada_build.vibration_features_10m in section B.
CREATE OR REPLACE TABLE jack_freeman_catalog.tech_summit_scada_build.vibration_features_seed (
  asset_id                STRING    NOT NULL,
  tag_id                  STRING    NOT NULL,
  window_start            TIMESTAMP NOT NULL,
  window_end              TIMESTAMP NOT NULL,
  rms_mm_s                DOUBLE,
  peak_mm_s               DOUBLE,
  crest_factor            DOUBLE,
  kurtosis                DOUBLE,
  stddev_mm_s             DOUBLE,
  sample_count            BIGINT,
  rms_delta_1h            DOUBLE,
  rms_delta_24h           DOUBLE,
  rms_slope_24h           DOUBLE,
  rms_pct_of_baseline     DOUBLE,
  bearing_temp_c          DOUBLE,
  motor_current_a         DOUBLE,
  throughput_tph          DOUBLE,
  run_minutes             DOUBLE,
  hours_since_maintenance DOUBLE,
  iso_10816_zone          STRING    COMMENT 'A|B|C|D',
  label_failure_30d       BOOLEAN   COMMENT 'training label: window falls within 30 days of an injected failure'
)
CLUSTER BY (asset_id, window_start)
COMMENT '120 days of synthetic 10-minute vibration features with injected failures. Static, written once in phase 0.';

-- Lane B trains against this view, not the table, so the live features can be
