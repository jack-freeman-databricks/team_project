  alert_id         STRING    NOT NULL,
  raised_at        TIMESTAMP NOT NULL,
  tag_id           STRING,
  asset_id         STRING,
  area_code        STRING,
  node_id          STRING             COMMENT 'set for imbalance rules, which are node-scoped',
  rule_id          STRING    NOT NULL,
  rule_name        STRING    NOT NULL,
  rule_type        STRING    NOT NULL,
  severity         STRING    NOT NULL COMMENT 'CRITICAL|HIGH|WARNING|INFO',
  trigger_value    DOUBLE,
  trigger_text     STRING,
